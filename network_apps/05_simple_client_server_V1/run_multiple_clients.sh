#!/bin/bash

# Проверяем, передано ли количество запусков
if [ $# -ne 3 ]; then
    echo "Использование: $0 <IP-адрес сервера> <порт сервера> <количество запусков>"
    exit 1
fi

SERVER_IP_ADDRESS=$1
SERVER_PORT=$2
NUMBER_OF_LAUNCHES=$3

# Функция проверки валидности IP-адреса сервера:
is_valid_ip() {
    local ip=$1
    
    if [[ $ip =~ ^([0-9]{1,3}\.){3}[0-9]{1,3}$ ]]; then
        
        for octet in $(echo "$ip" | tr '.' ' '); do
            if ((octet < 0 || octet > 255)); then
                return 1 # Невалидный IP-адрес
            fi
        done
        return 0  # Валидный IP-адрес
    else
        return 1  # Невалидный IP-адрес 
    fi
}

# Функция проверки валидности порта
is_valid_port() {
    local port=$1
    
    if [[ $port =~ ^[0-9]+$ ]] && ((port >= 1 && port <= 65535)); then
        return 0  # Валидный порт
    else
        return 1  # НЕвалидный порт
    fi
}


# Функция проверки, является ли строка числом
is_valid_number() {
    local number=$1
    
    if [[ $number =~ ^[0-9]+$ ]]; then
        return 0  # Валидное число
    else
        return -1  # НЕвалидное число
    fi
}

# Функция проверки, является ли количество запусков положительным числом
is_valid_nuber_of_launches() {
    local run_count=$1

    if ! is_valid_number "${run_count}"; then
        echo "Ошибка: аргумент должен быть положительным числом."
        return -1
    else
        return 0
    fi
}

# проверка валидности IP-адреса
if ! is_valid_ip "${SERVER_IP_ADDRESS}"; then
    echo "Ошибка: Невалидный IP-адрес: ${SERVER_IP_ADDRESS}"
    exit 1
fi

# Проверка того, что порт - это целое число от 1 до 65535
if ! is_valid_port "${SERVER_PORT}"; then
    echo "Ошибка: Невалидный порт: $PORT. Укажите значение от 1 до 65535."
    exit 1
fi

# Проверка того, что количество запусков является положительным числом
if ! [[ "${NUMBER_OF_LAUNCHES}" =~ ^[0-9]+$ ]]; then
    echo "Ошибка: аргумент должен быть положительным числом."
    exit 1
fi

# Запуск клиента NUMBER_OF_LAUNCHES раз
for ((i = 1; i <= NUMBER_OF_LAUNCHES; i++)); do
